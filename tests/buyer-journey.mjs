import assert from 'node:assert/strict';
import {PACKS,recommendPack,activeOffers,VERIFIED_OFFERS,escapeHtml} from '../scripts/buyer-catalog.js';
import {reminderDate} from '../scripts/portal/repeat-tools.js';
assert.equal(PACKS.length,5);
assert.equal(recommendPack({pack:'help',contents:'Fragile glass candles'}).id,'postal');
assert.equal(recommendPack({pack:'help',contents:'Hardback books'}).id,'book-wraps');
assert.equal(recommendPack({pack:'tape',contents:'books'}).id,'tape');
assert.equal(activeOffers('mailers').length,0,'Do not manufacture supplier pricing');
VERIFIED_OFFERS.push({pack:'mailers',verified:true,validUntil:'2026-10-01',scope:'Specific approved size and one-colour print',quantity:500,goods:400,setup:50,delivery:20,vat:94});
assert.equal(activeOffers('mailers','2026-09-16').length,1);
assert.equal(activeOffers('mailers','2026-10-02').length,0,'Expired offers must not appear');
VERIFIED_OFFERS[0].delivery=undefined;
assert.equal(activeOffers('mailers','2026-09-16').length,0,'Incomplete delivered costs must not appear');
VERIFIED_OFFERS.length=0;
assert.equal(escapeHtml('<img onerror="x">'),'&lt;img onerror=&quot;x&quot;&gt;');
const today=new Date(2026,8,16,12);
assert.equal(reminderDate(1000,50,10,today).getDate(),26);
assert.equal(reminderDate(100,50,10,today).getDate(),16,'Overdue stock replenishment is due today');
assert.throws(()=>reminderDate(100,0,10,today));
console.log('Passed: product routing, verified/expired/incomplete offers, HTML escaping, stock reminder timing.');
